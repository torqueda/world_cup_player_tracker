#!/usr/bin/env python3
"""
Write the site's TypeScript types and the data dictionary from the data contract.

data/contract/exports.yaml describes every JSON export. This script turns it
into:

- site/src/lib/data/types.ts: one interface per export, which the site uses
  for the imported JSON.
- docs/data_dictionary.md: the same description, for people.

Both files are generated: edit the contract and rerun this script. The test
tests/test_data_contract.py fails when a committed file differs from what the
script writes.

Usage:
    python scripts/export/generate_from_contract.py          # write both files
    python scripts/export/generate_from_contract.py --check  # exit 1 if either is out of date
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[2]
CONTRACT = REPO_ROOT / "data/contract/exports.yaml"
TYPES_TS = REPO_ROOT / "site/src/lib/data/types.ts"
DICTIONARY = REPO_ROOT / "docs/data_dictionary.md"

TS_TYPES = {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "list": "string[]"}
FORMATS = {
    "date": "YYYY-MM-DD",
    "datetime": "YYYY-MM-DDT00:00:00",
    "url": "URL",
}


def load_contract(path: Path = CONTRACT) -> dict:
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def ts_type(field: dict) -> str:
    if "values" in field:
        base = " | ".join(json.dumps(value, ensure_ascii=False) for value in field["values"])
    else:
        base = TS_TYPES[field["type"]]
    return f"{base} | null" if field.get("nullable") else base


def render_types(contract: dict) -> str:
    lines = [
        "// Generated by scripts/export/generate_from_contract.py from",
        "// data/contract/exports.yaml. Do not edit: change the contract and rerun",
        "// the script.",
    ]
    for name, table in contract.items():
        lines += ["", f"/** {table['file']}: {table['description']} */", f"export interface {table['type_name']} {{"]
        for field_name, field in table["fields"].items():
            lines.append(f"  /** {field['description']} */")
            lines.append(f"  {field_name}: {ts_type(field)};")
        lines.append("}")
    return "\n".join(lines) + "\n"


def cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def allowed(field: dict) -> str:
    parts = []
    if "values" in field:
        parts.append(", ".join(f"`{value}`" for value in field["values"]))
    if "format" in field:
        parts.append(FORMATS[field["format"]])
    if "pattern" in field:
        parts.append(f"`{field['pattern']}`")
    if "references" in field:
        parts.append(f"must exist in `{field['references']}`")
    return cell("; ".join(parts))


def render_dictionary(contract: dict) -> str:
    lines = [
        "# Data dictionary",
        "",
        "Generated by `scripts/export/generate_from_contract.py` from "
        "[`data/contract/exports.yaml`](../data/contract/exports.yaml). Do not edit: change the contract "
        "and rerun the script. The rules for changing the contract are in [data_contract.md](data_contract.md).",
        "",
        "Every export is a JSON list in `data/processed/app_exports/`, and every row has every field listed. "
        "`tests/test_data_contract.py` checks each row against these tables.",
        "",
        "| Export | One row is | Key | Read by the site |",
        "|---|---|---|---|",
    ]
    for name, table in contract.items():
        read_by = ", ".join(f"`{path.removeprefix('site/src/')}`" for path in table["read_by"]) or "No"
        lines.append(f"| [`{table['file']}`](#{name}) | {cell(table['description'])} | `{table['key']}` | {read_by} |")
    for name, table in contract.items():
        lines += [
            "",
            f"## {name}",
            "",
            cell(table["description"]),
            "",
            f"File `{table['file']}`, key `{table['key']}`, site type `{table['type_name']}`.",
            "",
            "| Field | Type | Can be null | Allowed values | Meaning |",
            "|---|---|---|---|---|",
        ]
        for field_name, field in table["fields"].items():
            type_name = "list of strings" if field["type"] == "list" else field["type"]
            lines.append(
                f"| `{field_name}` | {type_name} | {'yes' if field.get('nullable') else 'no'} | "
                f"{allowed(field)} | {cell(field['description'])} |"
            )
    return "\n".join(lines) + "\n"


def outputs(contract: dict) -> dict[Path, str]:
    return {TYPES_TS: render_types(contract), DICTIONARY: render_dictionary(contract)}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if a generated file is out of date")
    args = parser.parse_args()
    stale = []
    for path, text in outputs(load_contract()).items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(path)
        else:
            path.write_text(text, encoding="utf-8")
            print(f"Wrote {path.relative_to(REPO_ROOT)}")
    if stale:
        print("Out of date: " + ", ".join(str(path.relative_to(REPO_ROOT)) for path in stale), file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
