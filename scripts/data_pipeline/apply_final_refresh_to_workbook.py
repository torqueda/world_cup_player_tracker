#!/usr/bin/env python3
"""
Apply the post-final tournament data refresh directly to the master workbook.

Reads the fresh `data/processed/workbook_import/` sheets (regenerated by
`reconcile_final_rosters.py` + `build_workbook_import_sheets.py` against the
completed tournament) and upserts them into
`data/master/world_cup_2026_player_map_master.xlsx`:

1. squad_entries: update verified_at/status/shirt_number/caps in place
   (rosters were already final; this just re-verifies + updates squad_status
   for the 27 cut players).
2. player_stats: update goals/assists/minutes/cards/as_of_stage in place for
   all registered players, matched by player_id where possible and by the
   existing sheet's (team_code, fifa_listed_name) alias map for the ~21
   FIFA-vs-canonical name mismatches the user resolved by hand last cycle.
   Goalkeeping columns (gk_saves, gk_actions_inside_box,
   gk_actions_outside_box) are untouched — that source wasn't refreshed in
   this pass.
3. team_stats: update W/D/L/goals/xG/possession/stage_reached in place.
4. match_history: update the 4 previously-scheduled matches (2 semis,
   third-place playoff, final) with real scores. The semis keep their
   original match_id (team names didn't change); the third-place and final
   rows are matched by stage (their placeholder home/away were RU101/RU102
   and W101/W102) and get their match_id, teams, and scores replaced.
5. coaches / referees: upsert by id (unchanged personnel; just re-verifies).
6. sources: update the 5 existing FIFA/Wikipedia source rows' title/url/notes/
   accessed_at rather than appending duplicates (their source_ids already
   exist in the sheet from the original import).
7. Appends one change_log row documenting the refresh.

Writes a timestamped backup before saving.
"""

from __future__ import annotations

import csv
import shutil
from datetime import date
from pathlib import Path

from openpyxl import load_workbook

REPO_ROOT = Path(__file__).resolve().parents[2]
WB_PATH = REPO_ROOT / "data/master/world_cup_2026_player_map_master.xlsx"
IMPORT = REPO_ROOT / "data/processed/workbook_import"
TODAY = date.today().isoformat()


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        return list(csv.DictReader(handle))


def sheet_index(ws, id_col: int) -> dict[str, int]:
    """Map id value -> 1-indexed row number, skipping blank padding rows."""
    idx = {}
    for row in ws.iter_rows(min_row=2):
        val = row[id_col].value
        if val:
            idx[str(val)] = row[0].row
    return idx


def first_blank_row(ws, id_col: int) -> int:
    for row in ws.iter_rows(min_row=2):
        if row[id_col].value in (None, ""):
            return row[0].row
    return ws.max_row + 1


def main() -> None:
    backup = WB_PATH.with_name(f"world_cup_2026_player_map_master.backup_{TODAY}_final_refresh.xlsx")
    shutil.copy2(WB_PATH, backup)
    print(f"Backup written: {backup}")

    wb = load_workbook(WB_PATH)

    # ---- 1. squad_entries ---------------------------------------------------
    ws = wb["squad_entries"]
    headers = [c.value for c in ws[1]]
    col = {h: i for i, h in enumerate(headers)}
    idx = sheet_index(ws, col["squad_entry_id"])
    updated = 0
    for row in read_csv(IMPORT / "squad_entries_updates.csv"):
        r = idx.get(row["squad_entry_id"])
        if not r:
            continue
        ws.cell(r, col["shirt_number"] + 1).value = row.get("shirt_number") or None
        ws.cell(r, col["is_captain"] + 1).value = row.get("is_captain") or None
        ws.cell(r, col["squad_status"] + 1).value = row.get("squad_status") or None
        if row.get("caps_pre_tournament"):
            ws.cell(r, col["caps_pre_tournament"] + 1).value = row["caps_pre_tournament"]
        if row.get("goals_pre_tournament"):
            ws.cell(r, col["goals_pre_tournament"] + 1).value = row["goals_pre_tournament"]
        ws.cell(r, col["verified_at"] + 1).value = row.get("verified_at") or TODAY
        ws.cell(r, col["notes"] + 1).value = row.get("notes") or None
        updated += 1
    print(f"squad_entries: updated {updated} rows")

    # ---- 2. player_stats ------------------------------------------------------
    ws = wb["player_stats"]
    headers = [c.value for c in ws[1]]
    col = {h: i for i, h in enumerate(headers)}
    idx = sheet_index(ws, col["player_id"])

    # alias fallback: (team_code, fifa_listed_name) -> player_id, from the
    # sheet's own current rows (these are the ~21 FIFA-vs-canonical name
    # mismatches already resolved by hand in a prior import).
    alias_map = {}
    for row in ws.iter_rows(min_row=2):
        pid = row[col["player_id"]].value
        if not pid:
            continue
        key = (row[col["team_code"]].value, row[col["fifa_listed_name"]].value)
        alias_map[key] = pid

    stat_rows = read_csv(IMPORT / "player_stats.csv")
    unmatched = read_csv(IMPORT / "player_stats_unmatched_for_review.csv")
    still_unmatched = []
    updated = appended = 0
    for row in stat_rows + unmatched:
        pid = row.get("player_id") or ""
        if not pid:
            pid = alias_map.get((row["team_code"], row["fifa_listed_name"]), "")
        if not pid:
            still_unmatched.append(row)
            continue
        r = idx.get(pid)
        if r is None:
            r = first_blank_row(ws, col["player_id"])
            ws.cell(r, col["player_id"] + 1).value = pid
            ws.cell(r, col["tournament"] + 1).value = row.get("tournament") or "FIFA World Cup 2026"
            idx[pid] = r
            appended += 1
        else:
            updated += 1
        ws.cell(r, col["team_code"] + 1).value = row["team_code"]
        ws.cell(r, col["fifa_listed_name"] + 1).value = row["fifa_listed_name"]
        ws.cell(r, col["goals"] + 1).value = int(row["goals"])
        ws.cell(r, col["assists"] + 1).value = int(row["assists"])
        ws.cell(r, col["minutes_played"] + 1).value = int(row["minutes_played"])
        ws.cell(r, col["yellow_cards"] + 1).value = int(row["yellow_cards"])
        ws.cell(r, col["red_cards"] + 1).value = int(row["red_cards"])
        ws.cell(r, col["indirect_red_cards"] + 1).value = int(row["indirect_red_cards"])
        ws.cell(r, col["as_of_stage"] + 1).value = row["as_of_stage"]
        ws.cell(r, col["source_id"] + 1).value = row["source_id"]
        ws.cell(r, col["retrieved_at"] + 1).value = row["retrieved_at"]
    print(f"player_stats: updated {updated}, appended {appended}, still unmatched {len(still_unmatched)}")
    if still_unmatched:
        for row in still_unmatched:
            print(f"  UNMATCHED: {row['team_code']} {row['fifa_listed_name']}")

    # ---- 3. team_stats ----------------------------------------------------
    ws = wb["team_stats"]
    headers = [c.value for c in ws[1]]
    col = {h: i for i, h in enumerate(headers)}
    idx = sheet_index(ws, col["team_code"])
    updated = 0
    for row in read_csv(IMPORT / "team_stats.csv"):
        r = idx.get(row["team_code"])
        if not r:
            continue
        for field in (
            "matches_played", "wins", "draws", "losses", "goals_for", "goals_against",
            "stage_reached", "assists", "xg", "possession_pct", "as_of_stage",
            "source_id", "retrieved_at",
        ):
            value = row[field]
            if field in ("matches_played", "wins", "draws", "losses", "goals_for", "goals_against"):
                value = int(value)
            elif field == "xg":
                value = float(value)
            elif field == "possession_pct":
                value = int(value)
            ws.cell(r, col[field] + 1).value = value
        updated += 1
    print(f"team_stats: updated {updated} rows")

    # ---- 4. match_history ---------------------------------------------------
    ws = wb["match_history"]
    headers = [c.value for c in ws[1]]
    col = {h: i for i, h in enumerate(headers)}
    idx_by_id = sheet_index(ws, col["match_id"])
    idx_by_stage: dict[str, int] = {}
    for row in ws.iter_rows(min_row=2):
        stage = row[col["stage"]].value
        if stage in ("Play-off for third place", "Final"):
            idx_by_stage[stage] = row[0].row

    updated = 0
    for row in read_csv(IMPORT / "world_cup_history_matches.csv"):
        r = idx_by_id.get(row["match_id"])
        if r is None and row["stage"] in idx_by_stage:
            r = idx_by_stage[row["stage"]]
        if r is None:
            continue
        ws.cell(r, col["match_id"] + 1).value = row["match_id"]
        ws.cell(r, col["home_team"] + 1).value = row["home_team"]
        ws.cell(r, col["away_team"] + 1).value = row["away_team"]
        ws.cell(r, col["home_score"] + 1).value = int(row["home_score"])
        ws.cell(r, col["away_score"] + 1).value = int(row["away_score"])
        ws.cell(r, col["home_pens"] + 1).value = int(row["home_pens"]) if row["home_pens"] else None
        ws.cell(r, col["away_pens"] + 1).value = int(row["away_pens"]) if row["away_pens"] else None
        ws.cell(r, col["status"] + 1).value = row["status"]
        ws.cell(r, col["source_id"] + 1).value = row["source_id"]
        updated += 1
    print(f"match_history: updated {updated} rows")

    # ---- 5. coaches ---------------------------------------------------------
    ws = wb["coaches"]
    headers = [c.value for c in ws[1]]
    col = {h: i for i, h in enumerate(headers)}
    idx = sheet_index(ws, col["coach_id"])
    updated = appended = 0
    for row in read_csv(IMPORT / "coaches.csv"):
        r = idx.get(row["coach_id"])
        if r is None:
            ws.append([row.get(h, "") for h in headers])
            appended += 1
        else:
            ws.cell(r, col["coach_name"] + 1).value = row["coach_name"]
            ws.cell(r, col["coach_nationality"] + 1).value = row["coach_nationality"]
            ws.cell(r, col["retrieved_at"] + 1).value = row["retrieved_at"]
            updated += 1
    print(f"coaches: updated {updated}, appended {appended}")

    # ---- 6. referees ----------------------------------------------------------
    ws = wb["referees"]
    headers = [c.value for c in ws[1]]
    col = {h: i for i, h in enumerate(headers)}
    idx = sheet_index(ws, col["official_id"])
    updated = appended = 0
    for row in read_csv(IMPORT / "referees.csv"):
        r = idx.get(row["official_id"])
        if r is None:
            ws.append([row.get(h, "") for h in headers])
            appended += 1
        else:
            ws.cell(r, col["role"] + 1).value = row["role"]
            ws.cell(r, col["confederation"] + 1).value = row["confederation"]
            ws.cell(r, col["retrieved_at"] + 1).value = row["retrieved_at"]
            updated += 1
    print(f"referees: updated {updated}, appended {appended}")

    # ---- 7. sources ------------------------------------------------------------
    ws = wb["sources"]
    headers = [c.value for c in ws[1] if c.value]
    col = {h: i for i, h in enumerate(headers)}
    idx = sheet_index(ws, col["source_id"])
    updated = appended = 0
    for row in read_csv(IMPORT / "sources_new_rows.csv"):
        r = idx.get(row["source_id"])
        if r is None:
            new_row = [""] * len(headers)
            new_row[col["source_id"]] = row["source_id"]
            new_row[col["title"]] = row["source_name"]
            new_row[col["url"]] = row["url"]
            new_row[col["accessed_at"]] = row["retrieved_at"]
            new_row[col["notes"]] = row["notes"]
            ws.append(new_row)
            appended += 1
        else:
            ws.cell(r, col["title"] + 1).value = row["source_name"]
            ws.cell(r, col["url"] + 1).value = row["url"]
            ws.cell(r, col["accessed_at"] + 1).value = row["retrieved_at"]
            ws.cell(r, col["notes"] + 1).value = row["notes"]
            updated += 1
    print(f"sources: updated {updated}, appended {appended}")

    # ---- 8. change_log ----------------------------------------------------
    cl_ws = wb["change_log"]
    cl_ws.append(
        [
            f"chg_{TODAY}_post_final_refresh",
            TODAY,
            "ALL",
            "",
            "bulk_update",
            "player_stats, team_stats, match_history (semis/3rd-place/final), squad_entries verification, coaches, referees, sources",
            "through quarterfinals",
            "final",
            "https://www.fifa.com/en/tournaments/mens/worldcup/canadamexicousa2026/scores-fixtures",
            "user+claude",
            "Post-tournament refresh: re-ran the two Wikipedia scrapers and re-collected the three FIFA stat surfaces plus scores-fixtures from the browser pane. Resolved the semifinals (France 0-2 Spain, England 1-2 Argentina), third-place playoff (France 4-6 England), and final (Spain 1-0 Argentina aet). Rosters were unchanged since the pre-semifinal import (0 new players/clubs). Goalkeeping stats (gk_saves etc.) were not refreshed in this pass and remain at their through-quarterfinals values.",
        ]
    )
    print("change_log: appended 1 row")

    wb.save(WB_PATH)
    print(f"Saved workbook: {WB_PATH}")


if __name__ == "__main__":
    main()
